// Package sshkeys manages the SSH keys and config windevvm uses to reach VMs:
// one client key for the host, and a host key per VM generated on the host,
// so the first connection is verified rather than trusted on first use.
package sshkeys

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/pem"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"net"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"time"

	"golang.org/x/crypto/ssh"
)

// User is the login user inside every VM.
const User = "dev"

// Dir holds the client key, known_hosts and the generated ssh config.
type Dir struct {
	Path string
	mu   sync.Mutex
}

func (d *Dir) keyPath() string        { return filepath.Join(d.Path, "id_ed25519") }
func (d *Dir) KnownHostsPath() string { return filepath.Join(d.Path, "known_hosts") }

// ConfigPath is the generated ssh config, usable with ssh -F or Include.
func (d *Dir) ConfigPath() string { return filepath.Join(d.Path, "config") }

// ConfigRef writes path p for an ssh config. A path under the user's home
// becomes ~/..., which every ssh on Windows reads the same way. Git for
// Windows' ssh (which VS Code may pick) treats C:/... in an Include as
// relative to ~/.ssh, so it would silently skip the file.
func ConfigRef(p string) string {
	if home, err := os.UserHomeDir(); err == nil {
		if rel, err := filepath.Rel(home, p); err == nil && rel != "." && !strings.HasPrefix(rel, "..") && !filepath.IsAbs(rel) {
			return "~/" + filepath.ToSlash(rel)
		}
	}
	return filepath.ToSlash(p)
}

// KeyPath returns the client private key path, creating the key on first use.
func (d *Dir) KeyPath() (string, error) {
	if _, err := d.ensureKey(); err != nil {
		return "", err
	}
	return d.keyPath(), nil
}

// AuthorizedKey returns the client public key in authorized_keys format.
func (d *Dir) AuthorizedKey() (string, error) {
	signer, err := d.ensureKey()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(ssh.MarshalAuthorizedKey(signer.PublicKey()))) + " windevvm", nil
}

// Signer returns the client key for programmatic SSH.
func (d *Dir) Signer() (ssh.Signer, error) { return d.ensureKey() }

func (d *Dir) ensureKey() (ssh.Signer, error) {
	d.mu.Lock()
	defer d.mu.Unlock()
	b, err := os.ReadFile(d.keyPath())
	if errors.Is(err, fs.ErrNotExist) {
		if err := os.MkdirAll(d.Path, 0o700); err != nil {
			return nil, err
		}
		priv, _, err := NewKeyPair("windevvm client")
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(d.keyPath(), []byte(priv), 0o600); err != nil {
			return nil, err
		}
		b = []byte(priv)
	} else if err != nil {
		return nil, err
	}
	return ssh.ParsePrivateKey(b)
}

// NewKeyPair returns an ed25519 key as an OpenSSH private key PEM and an
// authorized_keys-format public key.
func NewKeyPair(comment string) (privPEM, pub string, err error) {
	pk, sk, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return "", "", err
	}
	block, err := ssh.MarshalPrivateKey(sk, comment)
	if err != nil {
		return "", "", err
	}
	sshPub, err := ssh.NewPublicKey(pk)
	if err != nil {
		return "", "", err
	}
	return string(pem.EncodeToMemory(block)), strings.TrimSpace(string(ssh.MarshalAuthorizedKey(sshPub))), nil
}

// Host is one VM's entry in known_hosts and the ssh config.
type Host struct {
	Alias   string // VM name
	IP      string
	HostKey string // authorized_keys format
}

// Sync rewrites known_hosts and the ssh config to exactly these hosts.
func (d *Dir) Sync(hosts []Host) error {
	key, err := d.KeyPath()
	if err != nil {
		return err
	}
	d.mu.Lock()
	defer d.mu.Unlock()
	sort.Slice(hosts, func(i, j int) bool { return hosts[i].Alias < hosts[j].Alias })

	var kh, cfg strings.Builder
	cfg.WriteString("# Generated by windevvm. Do not edit; it is rewritten on every change.\n")
	for _, h := range hosts {
		fields := strings.Fields(h.HostKey)
		if len(fields) < 2 {
			return fmt.Errorf("%s: bad host key", h.Alias)
		}
		fmt.Fprintf(&kh, "%s %s %s\n", h.Alias, fields[0], fields[1])
		fmt.Fprintf(&cfg, "\nHost %s\n", h.Alias)
		fmt.Fprintf(&cfg, "  HostName %s\n", h.IP)
		fmt.Fprintf(&cfg, "  User %s\n", User)
		fmt.Fprintf(&cfg, "  IdentityFile \"%s\"\n", ConfigRef(key))
		fmt.Fprintf(&cfg, "  IdentitiesOnly yes\n")
		fmt.Fprintf(&cfg, "  UserKnownHostsFile \"%s\"\n", ConfigRef(d.KnownHostsPath()))
		fmt.Fprintf(&cfg, "  HostKeyAlias %s\n", h.Alias)
		fmt.Fprintf(&cfg, "  StrictHostKeyChecking yes\n")
		fmt.Fprintf(&cfg, "  LogLevel ERROR\n")
	}
	if err := os.WriteFile(d.KnownHostsPath(), []byte(kh.String()), 0o600); err != nil {
		return err
	}
	return os.WriteFile(d.ConfigPath(), []byte(cfg.String()), 0o600)
}

// Dial opens an SSH connection to a VM, verifying its exact host key.
func (d *Dir) Dial(ip, hostKey string, timeout time.Duration) (*ssh.Client, error) {
	signer, err := d.Signer()
	if err != nil {
		return nil, err
	}
	pub, _, _, _, err := ssh.ParseAuthorizedKey([]byte(hostKey))
	if err != nil {
		return nil, fmt.Errorf("parse host key: %w", err)
	}
	return ssh.Dial("tcp", net.JoinHostPort(ip, "22"), &ssh.ClientConfig{
		User:            User,
		Auth:            []ssh.AuthMethod{ssh.PublicKeys(signer)},
		HostKeyCallback: ssh.FixedHostKey(pub),
		Timeout:         timeout,
	})
}

// Run executes a command over an SSH connection and returns its combined output.
func Run(c *ssh.Client, cmd string) (string, error) {
	s, err := c.NewSession()
	if err != nil {
		return "", err
	}
	defer s.Close()
	out, err := s.CombinedOutput(cmd)
	return string(out), err
}

// RunInput executes a command with stdin as its standard input and returns
// its combined output.
func RunInput(c *ssh.Client, cmd, stdin string) (string, error) {
	s, err := c.NewSession()
	if err != nil {
		return "", err
	}
	defer s.Close()
	s.Stdin = strings.NewReader(stdin)
	out, err := s.CombinedOutput(cmd)
	return string(out), err
}

// Stream executes a command with stdin as input (nil for none), copying its
// output to out as it arrives.
func Stream(c *ssh.Client, cmd string, stdin io.Reader, out io.Writer) error {
	s, err := c.NewSession()
	if err != nil {
		return err
	}
	defer s.Close()
	s.Stdin, s.Stdout, s.Stderr = stdin, out, out
	return s.Run(cmd)
}
