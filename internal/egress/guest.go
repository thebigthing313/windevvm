package egress

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
	"text/template"

	"windevvm/internal/secrets"
)

// Paths inside the VM.
const (
	GuestCACert   = "/usr/local/share/ca-certificates/windevvm.crt"
	GuestCABundle = "/etc/ssl/certs/ca-certificates.crt"
)

// gitHosts get a git credential helper that answers with the placeholder of
// a secret bound to them, so `git clone https://github.com/...` just works.
var gitHosts = []string{"github.com", "gitlab.com", "bitbucket.org", "codeberg.org"}

// Guest is the configuration pushed into a VM on every `windevvm up`.
type Guest struct {
	ProxyURL string // e.g. http://10.77.0.1:18010
	CACert   []byte // PEM
	// Placeholders maps secret names (the env var names) to placeholders.
	Placeholders map[string]string
	// Secrets are the in-use secrets' metadata, for git credentials.
	Secrets []secrets.Secret
}

// env returns the base settings followed by one entry per placeholder.
func (g Guest) env() (base, placeholders [][2]string, err error) {
	base = [][2]string{
		{"http_proxy", g.ProxyURL}, {"https_proxy", g.ProxyURL},
		{"HTTP_PROXY", g.ProxyURL}, {"HTTPS_PROXY", g.ProxyURL},
		{"no_proxy", "localhost,127.0.0.1,::1"}, {"NO_PROXY", "localhost,127.0.0.1,::1"},
		{"npm_config_proxy", g.ProxyURL}, {"npm_config_https_proxy", g.ProxyURL},
		{"NODE_USE_ENV_PROXY", "1"},
		{"NODE_EXTRA_CA_CERTS", GuestCACert},
		{"SSL_CERT_FILE", GuestCABundle},
		{"REQUESTS_CA_BUNDLE", GuestCABundle},
	}
	reserved := map[string]bool{"PATH": true, "HOME": true, "USER": true, "SHELL": true, "MISE_DATA_DIR": true, "MISE_CACHE_DIR": true}
	for _, kv := range base {
		reserved[strings.ToUpper(kv[0])] = true
	}
	names := make([]string, 0, len(g.Placeholders))
	for n := range g.Placeholders {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if err := secrets.ValidateName(n); err != nil {
			return nil, nil, err
		}
		if reserved[strings.ToUpper(n)] {
			return nil, nil, fmt.Errorf("secret name %s clashes with an environment variable windevvm sets; rename the secret", n)
		}
		placeholders = append(placeholders, [2]string{n, g.Placeholders[n]})
	}
	for _, kv := range append(append([][2]string(nil), base...), placeholders...) {
		if strings.ContainsAny(kv[1], "\"'\\$`\n\r;") {
			return nil, nil, fmt.Errorf("unsafe value for %s", kv[0])
		}
	}
	return base, placeholders, nil
}

func (g Guest) gitCredentials() [][2]string {
	byHost := map[string]string{}
	names := make([]string, 0, len(g.Secrets))
	bySecret := map[string]secrets.Secret{}
	for _, s := range g.Secrets {
		names = append(names, s.Name)
		bySecret[s.Name] = s
	}
	sort.Strings(names)
	for _, n := range names {
		s := bySecret[n]
		ph, ok := g.Placeholders[n]
		if !ok || !s.Allows(secrets.InHeader) {
			continue
		}
		for _, h := range s.Hosts {
			for _, gh := range gitHosts {
				if _, taken := byHost[gh]; strings.EqualFold(h, gh) && !taken {
					byHost[gh] = ph
				}
			}
		}
	}
	var out [][2]string
	for _, h := range gitHosts {
		if ph, ok := byHost[h]; ok {
			out = append(out, [2]string{h, ph})
		}
	}
	return out
}

var guestTmpl = template.Must(template.New("guest").Parse(`set -euo pipefail
umask 022
install -d -m 0755 /etc/windevvm /usr/local/share/ca-certificates

# Trust the windevvm CA (update-ca-certificates runs only when it changed).
cat > /etc/windevvm/ca.crt.new <<'WDVM_EOF'
{{.CACert}}WDVM_EOF
if cmp -s /etc/windevvm/ca.crt.new {{.CAPath}}; then
  rm -f /etc/windevvm/ca.crt.new
else
  mv /etc/windevvm/ca.crt.new {{.CAPath}}
  update-ca-certificates >/dev/null 2>&1
fi

# Environment: proxy settings, CA bundle paths and secret placeholders.
cat > /etc/windevvm/env <<'WDVM_EOF'
{{range .Env}}{{index . 0}}="{{index . 1}}"
{{end}}WDVM_EOF
tmp=$(mktemp)
sed '/^# BEGIN windevvm$/,/^# END windevvm$/d' /etc/environment > "$tmp" || true
{ echo '# BEGIN windevvm'; cat /etc/windevvm/env; echo '# END windevvm'; } >> "$tmp"
install -m 0644 "$tmp" /etc/environment
rm -f "$tmp"
cat > /etc/profile.d/windevvm-proxy.sh <<'WDVM_EOF'
# Generated by windevvm on every start.
{{range .Env}}export {{index . 0}}="{{index . 1}}"
{{end}}WDVM_EOF
chmod 0644 /etc/profile.d/windevvm-proxy.sh

# apt
cat > /etc/apt/apt.conf.d/95windevvm-proxy <<'WDVM_EOF'
Acquire::http::Proxy "{{.ProxyURL}}/";
Acquire::https::Proxy "{{.ProxyURL}}/";
WDVM_EOF

# git: proxy, plus credential helpers that answer with placeholders.
cat > /etc/windevvm/gitconfig <<'WDVM_EOF'
[http]
	proxy = {{.ProxyURL}}
{{range .Git}}[credential "https://{{index . 0}}"]
	helper =
	helper = "!f() { test \"$1\" = get || return 0; echo username=x-access-token; echo password={{index . 1}}; }; f"
{{end}}WDVM_EOF
chmod 0644 /etc/windevvm/gitconfig
git config --system --get-all include.path 2>/dev/null | grep -qxF /etc/windevvm/gitconfig || git config --system --add include.path /etc/windevvm/gitconfig

# Names of the secrets this VM has placeholders for, for windevvm doctor.
cat > /etc/windevvm/secrets <<'WDVM_EOF'
{{range .Names}}{{.}}
{{end}}WDVM_EOF
echo {{.Done}}
`))

// GuestDone is the last line the guest script prints on success.
const GuestDone = "WDVM-CONFIGURED"

// Script renders a bash script, run as root inside the VM, that applies g.
// It is idempotent.
func (g Guest) Script() (string, error) {
	if !strings.HasPrefix(g.ProxyURL, "http://") {
		return "", fmt.Errorf("bad proxy URL %q", g.ProxyURL)
	}
	if !bytes.HasPrefix(bytes.TrimSpace(g.CACert), []byte("-----BEGIN CERTIFICATE-----")) || bytes.Contains(g.CACert, []byte("WDVM_EOF")) {
		return "", fmt.Errorf("bad CA certificate")
	}
	base, phs, err := g.env()
	if err != nil {
		return "", err
	}
	cert := string(g.CACert)
	if !strings.HasSuffix(cert, "\n") {
		cert += "\n"
	}
	var names []string
	for _, kv := range phs {
		names = append(names, kv[0])
	}
	var b bytes.Buffer
	err = guestTmpl.Execute(&b, map[string]any{
		"CACert": cert, "CAPath": GuestCACert, "Env": append(base, phs...), "ProxyURL": g.ProxyURL,
		"Git": g.gitCredentials(), "Names": names, "Done": GuestDone,
	})
	return b.String(), err
}
